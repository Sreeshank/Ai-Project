-- Private document repository. Original bytes live in PostgreSQL bytea, not
-- storage.objects. No browser grants or public bucket are required.
create schema if not exists campus;
revoke all on schema campus from public;

create table if not exists campus.documents (
 id text primary key, title text not null, department text not null,
 status text not null check(status in ('pending','approved','archived')),
 created_at text not null, expires_on text, sample integer not null default 0,
 filename text not null, media_type text not null, original bytea not null);
create table if not exists campus.chunks (
 id bigint generated by default as identity primary key,
 document_id text not null references campus.documents(id),
 page integer not null, text text not null,
 search tsvector generated always as (to_tsvector('english', text)) stored);
create index if not exists campus_chunk_document on campus.chunks(document_id);
create index if not exists campus_chunk_search on campus.chunks using gin(search);
create table if not exists campus.document_pages (
 document_id text references campus.documents(id), page integer not null,
 text text not null, method text not null, warnings text not null default '[]',
 confidence double precision, reviewed integer not null default 0,
 primary key(document_id,page));
create table if not exists campus.document_revisions (
 id text primary key, document_id text references campus.documents(id),
 created_at text not null, reason text not null, pages text not null);
create table if not exists campus.answers (id text primary key, question text, payload text);
create table if not exists campus.feedback (
 id text primary key, answer_id text references campus.answers(id), helpful integer, created_at text);
create table if not exists campus.vector_jobs (
 document_id text primary key, token text not null,
 attempts integer not null default 0, next_attempt double precision not null default 0, error text);
create table if not exists campus.embedding_cache (
 cache_key text primary key, model text not null, dimensions integer not null, embedding text not null);
create table if not exists campus.vector_manifest (
 document_id text primary key, revision text not null, model text not null,
 chunks integer not null, indexed_at double precision not null);

create or replace function campus.enqueue_vector_change() returns trigger
language plpgsql set search_path = pg_catalog, campus as $$
declare identifier text;
begin
 if TG_TABLE_NAME='documents' then
   identifier := NEW.id;
 elsif TG_OP='DELETE' then
   identifier := OLD.document_id;
 else
   identifier := NEW.document_id;
 end if;
 insert into campus.vector_jobs(document_id,token)
 values(identifier,md5(random()::text || clock_timestamp()::text))
 on conflict(document_id) do update set token=excluded.token,attempts=0,next_attempt=0,error=null;
 return null;
end $$;
drop trigger if exists vector_document_change on campus.documents;
create trigger vector_document_change after insert or update on campus.documents
 for each row execute function campus.enqueue_vector_change();
drop trigger if exists vector_chunk_change on campus.chunks;
create trigger vector_chunk_change after insert or update or delete on campus.chunks
 for each row execute function campus.enqueue_vector_change();

alter table campus.documents enable row level security;
